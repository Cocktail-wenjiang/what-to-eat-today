/**
 * 植物性例外（含荤食关键词但实为素食的食材）
 * 判定时先剔除这些词再匹配，避免误伤。
 */
const PLANT_EXCEPTIONS = ['牛油果', '牛蒡']

/** 判断单一食材是否含荤 */
export function isMeatIngredient(name) {
  let probe = name
  for (const ex of PLANT_EXCEPTIONS) probe = probe.split(ex).join('')
  return MEAT_KEYWORDS.some((kw) => probe.includes(kw))
}

