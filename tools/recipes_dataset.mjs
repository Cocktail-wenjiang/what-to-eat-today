/** 依据食材与额外标签推导核心口味标签 */
export function deriveCoreTags(ingredients, extraTags = []) {
  const tags = new Set()

  // 显式额外标签中的口味直接采用
  for (const t of extraTags) {
    if (CORE_PREFERENCES.includes(t)) tags.add(t)
  }

  // 鸡蛋不算荤（蛋奶素），单独排除
  const hasMeat = ingredients.some((i) => i !== '鸡蛋' && isMeatIngredient(i))

  // 素食：不含肉/禽/水产
  if (!hasMeat) tags.add('素食')
  // 高蛋白：含肉蛋海鲜
  const hasProtein = hasMeat || ingredients.includes('鸡蛋')
  if (hasProtein) tags.add('高蛋白')

  // 清淡：指少油少盐、清蒸/清炖/凉拌路线，与「是否含肉」无关
  // （清蒸鱼、炖排骨汤同样属于清淡，不能因为含荤就排除）
  const lightish = ['低脂', '清淡', '汤', '凉菜'].some((t) => extraTags.includes(t))
  if (lightish) tags.add('清淡')

  return tags
}

/** 组装最终菜谱列表 */
export function buildRecipes() {
  return RAW.map(([name, ingredients, briefSteps, minutes, extraTags], idx) => {
    const core = deriveCoreTags(ingredients, extraTags)
    const allExtra = extraTags.filter((t) => !CORE_PREFERENCES.includes(t))
    // 核心口味在前，额外标签在后，保证「快捷」按用时兜底
    if (minutes <= 15) core.add('快捷')

    const tags = [...new Set([...core, ...allExtra])]
    const recipeId = 'R-' + String(idx + 1).padStart(3, '0')
    // 优先使用 recipes_steps.mjs 里的详细制作过程；
    // 若缺失则回退到 RAW 中的简要步骤，保证构建永不因漏写而中断。
    const steps = STEPS[recipeId] || briefSteps
    return {
      recipeId,
      name,
      ingredients,
      steps,
      minutes,
      tags,
    }
  })
}

export default buildRecipes
